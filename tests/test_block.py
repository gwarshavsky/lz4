class TestRoundTrip:
    """Test compress -> decompress round-trip with various data patterns."""

    def test_empty(self, empty_data):
        c = compress(empty_data)
        d = decompress(c, uncompressed_size=0)
        assert d == empty_data

    def test_small_text(self, small_text):
        c = compress(small_text)
        d = decompress(c, uncompressed_size=len(small_text))
