class TestPartialDecompression:
    """Test partial decompression, ported from decompress-partial.c."""

    def test_partial_basic(self):
        """Core test from decompress-partial.c."""
        source = (
            b"Lorem ipsum dolor sit amet, consectetur adipiscing elit, "
            b"sed do eiusmod tempor incididunt ut labore et dolore magna aliqua. "
            b"Ut enim ad minim veniam, quis nostrud exercitation ullamco laboris "
            b"nisi ut aliquip ex ea commodo consequat. Duis aute irure dolor in "
            b"reprehenderit in voluptate velit esse cillum dolore eu fugiat nulla "
            b"pariatur. Excepteur sint occaecat cupidatat non proident, sunt in "
            b"culpa qui officia deserunt mollit anim id est laborum. "
            b"Lorem ipsum dolor sit amet, consectetur adipiscing elit, "
            b"sed do eiusmod tempor incididunt ut labore et dolore magna aliqua. "
        )
        src_len = len(source)

        # Compress
        compressed = compress(source)
        cmp_size = len(compressed)

        # Test partial decompression with varying srcSize (cmpSize .. cmpSize+9)
        buffer_size = 2 * src_len
        for i in range(cmp_size, cmp_size + 10):
            # Pad compressed data if needed
            padded = compressed + b'\x00' * max(0, i - cmp_size)
            result = decompress_partial(padded, i, src_len, buffer_size)
            assert len(result) >= src_len, (
                f"Partial decompression returned only {len(result)} bytes "
                f"for srcSize={i}, expected at least {src_len}"
            )
            assert result[:src_len] == source

    def test_partial_various_targets(self):
        """Test partial decompression with various target sizes."""
        data = generate_buffer(10000, match_proba=0.5, seed=42)
        compressed = compress(data)
        cmp_size = len(compressed)

        for target in [1, 10, 100, 1000, 5000, len(data)]:
            result = decompress_partial(
                compressed, cmp_size, target, target
            )
            assert len(result) <= target
            assert result == data[:len(result)]


