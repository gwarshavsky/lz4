class TestCompressDestSize:
    """Test compress_dest_size() for fixed-output-size compression."""

    def test_basic(self):
        data = generate_buffer(10000, match_proba=0.5, seed=42)
        target = 5000
        compressed, consumed = compress_dest_size(data, target)
        assert len(compressed) <= target
        assert consumed <= len(data)
        # The consumed portion should decompress correctly
        d = decompress(compressed, uncompressed_size=consumed)
        assert d == data[:consumed]

    def test_large_target(self):
        data = generate_buffer(1000, match_proba=0.5, seed=42)
        target = compress_bound(len(data))
        compressed, consumed = compress_dest_size(data, target)
        assert consumed == len(data)  # Everything should be consumed


