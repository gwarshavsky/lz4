class TestDictionaryDecompression:
    """Test dictionary-based decompression."""

    def test_no_dict(self):
        """Scenario 1: No dictionary (dict=NULL, dictSize=0)."""
        source = (
            b"Lorem ipsum dolor sit amet, consectetur adipiscing elit, "
            b"sed do eiusmod tempor incididunt ut labore et dolore magna aliqua. "
            b"Ut enim ad minim veniam, quis nostrud exercitation ullamco laboris "
            b"nisi ut aliquip ex ea commodo consequat. "
        )
        compressed = compress(source)
        cmp_size = len(compressed)

        for i in range(cmp_size, cmp_size + 10):
            padded = compressed + b'\x00' * max(0, i - cmp_size)
            result = decompress_partial_using_dict(
                padded, i, len(source), 2 * len(source),
                None, 0,
            )
            assert len(result) >= len(source)
            assert result[:len(source)] == source

    def test_with_external_dict(self):
        """Test decompression with external dictionary data."""
        # Create dict-compressed data: use the streaming encoder
        enc = LZ4StreamEncode()
        dict_data = generate_buffer(4096, match_proba=0.5, seed=100)
        enc.load_dict(dict_data)

        source = generate_buffer(4096, match_proba=0.5, seed=200)
        compressed = enc.compress_continue(source, max_output_size=compress_bound(len(source)))

        # Decompress using the dictionary
        result = decompress_using_dict(
            compressed, len(compressed), len(source),
            dict_data, len(dict_data),
        )
        assert result == source


