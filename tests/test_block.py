class TestErrorHandling:
    """Test error handling for invalid inputs."""

    def test_decompress_truncated(self):
        """Truncated compressed data should raise an error."""
        data = generate_buffer(1000, match_proba=0.5, seed=42)
        compressed = compress(data)
        # Truncate the compressed data
        truncated = compressed[:len(compressed) // 2]
        with pytest.raises(LZ4DecompressError):
            decompress(truncated, uncompressed_size=len(data))

    def test_decompress_corrupted(self):
        """Corrupted compressed data should raise or return wrong result.

        Note: LZ4 block format corruption may not always be detected;
        the decompressor is allowed to produce wrong output. We test that
        at minimum, the output differs from the original.
        """
        data = generate_buffer(1000, match_proba=0.5, seed=42)
        compressed = bytearray(compress(data))
        # Corrupt the middle of the compressed data
        if len(compressed) > 10:
            compressed[len(compressed) // 2] ^= 0xFF
        try:
            result = decompress(bytes(compressed), uncompressed_size=len(data))
            # If no error was raised, the result should differ from original
            assert result != data, "Corrupted data decompressed to original"
        except LZ4DecompressError:
            pass  # Expected

    def test_decompress_wrong_size(self):
        """Wrong uncompressed_size should raise an error."""
        data = b"test data" * 100
        compressed = compress(data)
        with pytest.raises(LZ4DecompressError):
            decompress(compressed, uncompressed_size=len(data) // 2)

    def test_compress_negative_max_output(self):
        """Negative max_output_size should raise."""
        with pytest.raises(LZ4CompressError):
            compress(b"x", max_output_size=-1)

    def test_decompress_empty_input(self):
        """Empty input should raise."""
        with pytest.raises(LZ4DecompressError):
            decompress(b"", uncompressed_size=100)

    def test_decompress_zero_offset(self):
        """A block with a zero offset should be detected as corrupted."""
        # Craft a malicious block: token=0x10 (1 literal, 0 match len) + literal + offset=0
        malicious = bytes([0x10, 0x41, 0x00, 0x00])  # token, literal 'A', offset=0
        with pytest.raises(LZ4DecompressError):
            decompress(malicious, uncompressed_size=100)


