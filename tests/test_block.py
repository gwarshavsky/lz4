class TestStreaming:
    """Test LZ4StreamEncode and LZ4StreamDecode."""

    def test_basic_stream_roundtrip(self):
        """Compress and decompress independent blocks via streaming API."""
        enc = LZ4StreamEncode()

        blocks = [
            generate_buffer(1000, match_proba=0.5, seed=i)
            for i in range(5)
        ]

        # Each block compressed independently (no cross-block references)
        for i, block in enumerate(blocks):
            enc.reset()
            c = enc.compress_continue(block)
            d = decompress(c, uncompressed_size=len(block))
            assert d == block, f"Stream block {i} mismatch"

    def test_load_dict(self):
        """Test loading a dictionary and compressing."""
        enc = LZ4StreamEncode()
        dict_data = generate_buffer(32768, match_proba=0.5, seed=42)
        loaded = enc.load_dict(dict_data)
        assert loaded == len(dict_data)

        data = generate_buffer(4096, match_proba=0.5, seed=100)
        compressed = enc.compress_continue(data)
        assert len(compressed) > 0

    def test_save_dict(self):
        """Test saving dictionary after compression."""
        enc = LZ4StreamEncode()
        data = generate_buffer(10000, match_proba=0.5, seed=42)
        enc.compress_continue(data)

        saved = enc.save_dict(4096)
        assert len(saved) <= 4096
        assert len(saved) > 0

    def test_stream_reset(self):
        """Test reset clears state properly."""
        enc = LZ4StreamEncode()
        data = generate_buffer(1000, match_proba=0.5, seed=42)
        enc.compress_continue(data)

        enc.reset()
        # Should be able to compress again from scratch
        c = enc.compress_continue(data)
        assert len(c) > 0


