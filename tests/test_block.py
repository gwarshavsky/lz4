class TestCompressBound:
    """Tests for compress_bound()."""

    def test_zero(self):
        assert compress_bound(0) == 16

    def test_small(self):
        assert compress_bound(1) == 17

    def test_typical(self):
        assert compress_bound(1000) == 1000 + 1000 // 255 + 16

    def test_large(self):
        result = compress_bound(1_000_000)
        assert result > 1_000_000

    def test_negative(self):
        assert compress_bound(-1) == 0

    def test_too_large(self):
        assert compress_bound(LZ4_MAX_INPUT_SIZE + 1) == 0

    def test_max_input(self):
        result = compress_bound(LZ4_MAX_INPUT_SIZE)
        assert result > LZ4_MAX_INPUT_SIZE


