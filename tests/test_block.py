    def test_all_zeros(self, all_zeros):
        c = compress(all_zeros)
        d = decompress(c, uncompressed_size=len(all_zeros))
        assert d == all_zeros

    def test_pattern(self, pattern_data):
        c = compress(pattern_data)
        d = decompress(c, uncompressed_size=len(pattern_data))
        assert d == pattern_data

    def test_random(self, random_data):
        c = compress(random_data)
